//! English names of the ISO 639-1 languages, for a track whose language tag names one.
//!
//! Generated from Debian's iso-codes 4.16.0 (`/usr/share/iso-codes/json/iso_639-2.json`, the
//! entries that carry a two-letter code; a name with alternatives keeps its first, and the eight
//! inverted or qualified names are put in reading order: "Greek", "North Ndebele"). Names are
//! data, not translated application strings.

/// The English name of the ISO 639-1 language `code`, or `code` itself when it names none.
pub fn label(code: &str) -> &str {
    NAMES
        .binary_search_by(|(c, _)| (*c).cmp(code))
        .map_or(code, |i| NAMES[i].1)
}

