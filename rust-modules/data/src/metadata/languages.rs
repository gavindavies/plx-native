#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_names_every_code_once() {
        assert!(NAMES.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(NAMES.iter().all(|(c, n)| c.len() == 2 && !n.is_empty()));
    }

    #[test]
    fn a_known_code_reads_as_its_name_and_anything_else_as_itself() {
        assert_eq!(label("en"), "English");
        assert_eq!(label("de"), "German");
        assert_eq!(label("nl"), "Dutch");
        assert_eq!(label("xx"), "xx");
        assert_eq!(label(""), "");
    }
}
